// Builds importable n8n workflows from workflow-templates/*.json.
// A Code node whose jsCode is "{{code:nodes/<file>.js}}" gets that file's
// contents, with its "// @include <path>" lines replaced by the included files.
//
//   node scripts/build-workflows.mjs

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = join(root, "workflow-templates");
const outDir = join(root, "workflows");
const codeDir = join(root, "code");

const PLACEHOLDER = /^\{\{code:(.+)\}\}$/;

export function bundle(file) {
    const source = readFileSync(file, "utf8");

    return source.replace(/^\/\/ @include (.+)$/gm, (_, rel) => {
        const included = resolve(dirname(file), rel.trim());
        return `// ---- ${rel.trim()} ----\n${readFileSync(included, "utf8").trim()}\n`;
    });
}

function build() {
    for (const name of readdirSync(templatesDir).filter(f => f.endsWith(".json"))) {
        const workflow = JSON.parse(readFileSync(join(templatesDir, name), "utf8"));

        for (const node of workflow.nodes) {
            const match = PLACEHOLDER.exec(node.parameters?.jsCode || "");
            if (match) {
                node.parameters.jsCode = "// Generated by scripts/build-workflows.mjs. Edit n8n/code/, not here.\n" +
                    bundle(join(codeDir, match[1]));
            }
        }

        writeFileSync(join(outDir, name), JSON.stringify(workflow, null, 2) + "\n");
        console.log("built workflows/" + name);
    }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    build();
}
